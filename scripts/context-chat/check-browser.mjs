import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(path.join(root, 'app/builds/typescript/client_web/package.json'));
const { chromium, expect } = require('@playwright/test');
const target = new URL(process.env.CONTEXT_CHAT_URL ?? 'http://127.0.0.1:5129');
if (!['127.0.0.1', 'localhost'].includes(target.hostname) || target.username || target.password || target.search || target.hash) throw new Error('Use an isolated loopback synthetic runtime');
if (process.env.CONTEXT_CHAT_ALLOW_SYNTHETIC !== '1') throw new Error('Explicit synthetic runtime opt-in required');
const output = process.env.CONTEXT_CHAT_OUTPUT ?? '/private/tmp/ryadom-context-chat';
const note = 'Личная заметка: моя кодовая фраза — «янтарный маяк 47». Мне удобно обсуждать подготовку по вторникам в 19:00, короткими встречами по 25 минут.';
const report = { status: 'FAIL', mode: 'live-provider/operator-configured', startedAt: new Date().toISOString(), sourceSha: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim(), checks: [], generalAgentRequests: 0 };
let browser;
let stage = 'start';
const check = (name, details = {}) => report.checks.push({ name, status: 'PASS', ...details });
try {
  await mkdir(output, { recursive: true });
  browser = await chromium.launch({ channel: 'chrome' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(20_000);
  page.on('request', (request) => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/message') report.generalAgentRequests++; });
  const response = (suffix, method = 'GET') => page.waitForResponse((item) => new URL(item.url()).pathname.endsWith(suffix) && item.request().method() === method, { timeout: 150_000 });
  const fit = async () => {
    await page.evaluate(async () => { await document.fonts.ready; await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))); });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Horizontal viewport overflow');
    assert.equal(await page.locator('.cc-topbar').count(), 1);
    const bounds = await page.locator('.cc-composer-area').boundingBox();
    const viewport = page.viewportSize();
    assert(bounds && bounds.y >= 0 && bounds.y + bounds.height <= viewport.height + 1, 'Composer must fit inside the viewport');
  };
  const send = async (message) => {
    await page.getByLabel('Ваше сообщение', { exact: true }).fill(message);
    const waiting = response('/goals/demo/chat', 'POST');
    await page.getByRole('button', { name: /^Отправить сообщение(?: снова)?$/ }).click();
    const reply = await waiting;
    assert.equal(reply.status(), 200, `Chat HTTP ${reply.status()}`);
    const result = await reply.json();
    await expect(page.locator('.cc-message-assistant').last().locator('.cc-bubble')).toHaveText(result.reply.text);
    await expect(page.getByLabel('Ваше сообщение', { exact: true })).toHaveValue('');
    return result;
  };
  stage = 'ordinary-signup';
  await page.goto(`${target.origin}/app`);
  await expect(page.locator('#username')).toBeVisible();
  await page.locator('#username').fill('context-chat-synthetic');
  await page.locator('#new-password').fill('Synthetic-Context-Chat-2026!');
  await page.locator('#confirm-password').fill('Synthetic-Context-Chat-2026!');
  const signup = response('/auth/signup', 'POST');
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click();
  assert.equal((await signup).status(), 201);
  check('ordinary synthetic signup');
  stage = 'empty-context';
  await page.getByRole('button', { name: 'Чат с агентом', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Чат с агентом', exact: true })).toBeVisible();
  const empty = await send('Какая у меня цель?');
  assert.equal(empty.reply.outcome, 'insufficient_context');
  assert.deepEqual(empty.reply.citations, []);
  check('no context gives explicit insufficient-context response');
  await page.getByRole('button', { name: 'К моей цели', exact: true }).click();
  stage = 'goal-and-context-through-ui';
  await page.getByRole('button', { name: /Заполнить пример про ML-стажировку/ }).click();
  const goalSaved = response('/goals/demo', 'PUT');
  await page.getByRole('button', { name: /Подтвердить цель и критерии/ }).click();
  assert.equal((await goalSaved).status(), 200);
  await page.getByRole('button', { name: 'Добавить контекст', exact: true }).click();
  await page.getByLabel('Название источника', { exact: true }).fill('Личные предпочтения для чата');
  await page.getByLabel(/^Текст источника/).fill(note);
  const imported = response('/context/import', 'POST');
  await page.getByRole('button', { name: 'Найти события', exact: true }).click();
  const importedResponse = await imported;
  assert.equal(importedResponse.status(), 200);
  const sourceResult = await importedResponse.json();
  assert.equal(sourceResult.source.text, note);
  check('goal and actual context import via UI', { extractedEvidence: sourceResult.evidence.length });
  stage = 'grounded-chat';
  await page.getByRole('button', { name: 'Чат с агентом', exact: true }).click();
  let result = await send('Какая моя кодовая фраза?');
  assert.equal(result.reply.outcome, 'grounded');
  assert(result.reply.text.includes('янтарный маяк 47'));
  assert(result.reply.citations.length > 0);
  for (const citation of result.reply.citations) {
    assert.equal(citation.sourceId, sourceResult.source.id);
    assert.equal(note.slice(citation.textStart, citation.textEnd), citation.quote);
  }
  assert.equal(result.reply.text, `В твоих материалах есть записи:\n\n${result.reply.citations.map((citation) => `«${citation.quote}»`).join('\n\n')}`);
  const citation = page.locator('.cc-message-assistant').last().getByRole('button', { name: /^Источник/ }).first();
  await citation.click();
  await expect(page.locator('.cc-message-assistant').last().locator('blockquote')).toContainText('янтарный маяк 47');
  await fit();
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
  check('actual model selects exact saved source and citation opens');
  stage = 'unsupported-question';
  result = await send('Какая сейчас погода в Париже? Используй только мои сохранённые материалы.');
  assert.equal(result.reply.outcome, 'insufficient_context');
  assert.deepEqual(result.reply.citations, []);
  assert(!/солнечно|дождь|градус/i.test(result.reply.text));
  check('out-of-context question refuses without external facts');
  stage = 'reload-history';
  const expectedMessages = result.messages;
  const loaded = response('/goals/demo/chat');
  await page.reload();
  assert.deepEqual((await (await loaded).json()).messages, expectedMessages);
  await expect(page.locator('.cc-message')).toHaveCount(expectedMessages.length);
  assert.equal(new URL(page.url()).pathname, '/chat');
  check('deep-link reload restores server history exactly', { messages: expectedMessages.length });
  stage = 'draft-and-mobile';
  await page.getByLabel('Ваше сообщение', { exact: true }).fill('Несохранённый черновик');
  await page.getByRole('button', { name: 'К моей цели', exact: true }).click();
  await page.getByRole('button', { name: 'Чат с агентом', exact: true }).click();
  await expect(page.getByLabel('Ваше сообщение', { exact: true })).toHaveValue('Несохранённый черновик');
  await page.getByLabel('Ваше сообщение', { exact: true }).fill('');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 375, height: 844 });
  await fit();
  await expect(page.getByLabel('Ваше сообщение', { exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 812, height: 375 });
  await fit();
  await expect(page.getByLabel('Ваше сообщение', { exact: true })).toBeVisible();
  check('draft survives back/return; mobile and landscape fit; reduced motion');
  assert.equal(report.generalAgentRequests, 0);
  check('no unrestricted general-agent request');
  report.status = 'PASS';
} catch (error) {
  report.failure = { stage, type: error?.constructor?.name ?? 'Error', message: String(error?.message ?? 'Unknown failure').slice(0, 900) };
  process.exitCode = 1;
} finally {
  await browser?.close();
  report.finishedAt = new Date().toISOString();
  await writeFile(path.join(output, 'results.json'), JSON.stringify(report, null, 2) + '\n', { mode: 0o600 });
  console.log(JSON.stringify(report));
}
