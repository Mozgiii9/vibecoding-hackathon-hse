#!/usr/bin/env node
/** Record the real authenticated text workflow without fixtures or direct API mutations. */
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sourceBody = 'Синтетическая демонстрационная заметка Рядом. Сегодня провели одно пробное ML-интервью с наставником.';
const goalTitle = 'Подготовиться к ML-собеседованию';
const criterionDescriptions = ['Пройти пробные интервью', 'Провести пробные интервью'];
const goalPath = '/api/goals/demo';

class RecordingError extends Error {
  constructor(code) { super(code); this.code = code; }
}

/** Fail with an allowlisted code rather than a raw error containing request or login data. */
function requireCondition(condition, code) {
  if (!condition) throw new RecordingError(code);
}

/** Resolve an output location inside this repository, rejecting existing symlink escapes. */
async function outputLocation(value) {
  const output = path.resolve(projectRoot, value || 'output/playwright/ryadom-recordings');
  const root = await fs.realpath(projectRoot);
  requireCondition(output.startsWith(`${projectRoot}${path.sep}`), 'OUTPUT_OUTSIDE_REPOSITORY');
  let ancestor = output;
  while (true) {
    try {
      const real = await fs.realpath(ancestor);
      requireCondition(real === root || real.startsWith(`${root}${path.sep}`), 'OUTPUT_SYMLINK_ESCAPE');
      break;
    } catch (error) {
      if (error instanceof RecordingError || error.code !== 'ENOENT') throw error;
      ancestor = path.dirname(ancestor);
    }
  }
  // Protect source/config directories even when the requested directory is inside the repo.
  const relative = path.relative(projectRoot, output);
  const recordings = path.join('docs', 'demo', 'defense', 'recordings');
  requireCondition(relative.startsWith(`output${path.sep}`) || relative === recordings || relative.startsWith(`${recordings}${path.sep}`), 'OUTPUT_LOCATION_NOT_RECORDINGS');
  return output;
}

/** Validate operator configuration before creating files or launching the browser. */
async function configuration() {
  const target = process.env.RYADOM_DEMO_URL;
  const username = process.env.RYADOM_DEMO_USERNAME ?? process.env.USERNAME;
  const password = process.env.RYADOM_DEMO_PASSWORD ?? process.env.PASSWORD;
  requireCondition(target && username && password, 'MISSING_URL_OR_SYNTHETIC_CREDENTIALS');
  let url;
  try { url = new URL(target); } catch { throw new RecordingError('INVALID_URL'); }
  requireCondition(['http:', 'https:'].includes(url.protocol), 'UNSUPPORTED_URL_PROTOCOL');
  requireCondition(!url.username && !url.password && !url.search && !url.hash, 'URL_MUST_NOT_CONTAIN_CREDENTIALS_QUERY_OR_HASH');
  requireCondition(url.protocol === 'https:' || ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname), 'REMOTE_HTTP_CREDENTIALS_FORBIDDEN');
  requireCondition(url.pathname === '/' || url.pathname === '/login', 'UNEXPECTED_UI_PATH');
  requireCondition(!process.env.RYADOM_DEMO_AUDIO_PATH, 'AUDIO_AUTOMATION_NOT_IMPLEMENTED');
  const sha = process.env.RYADOM_DEMO_SHA || null;
  requireCondition(sha === null || /^[a-f\d]{7,40}$/i.test(sha), 'INVALID_CANDIDATE_SHA');
  const timeout = Number(process.env.RYADOM_DEMO_TIMEOUT_MS || 90000);
  requireCondition(Number.isInteger(timeout) && timeout >= 5000 && timeout <= 300000, 'INVALID_TIMEOUT');
  return { url: url.href, origin: url.origin, username, password, sha, timeout,
    output: await outputLocation(process.env.RYADOM_DEMO_OUTPUT_DIR ?? process.env.OUTPUT_DIR) };
}

/** Match only responses generated by this page on the configured UI origin. */
function matchesResponse(response, origin, pathname, method) {
  const url = new URL(response.url());
  return url.origin === origin && url.pathname === pathname && response.request().method() === method;
}

/** Read a real successful response without persisting its body or upstream error message. */
async function payload(response, code) {
  requireCondition(response.ok(), `${code}_HTTP_${response.status()}`);
  try { return await response.json(); } catch { throw new RecordingError(`${code}_INVALID_JSON`); }
}

/** Require a unique visible selector so ambiguous rows can never trigger confirmation. */
async function uniqueVisible(locator, code) {
  await locator.waitFor({ state: 'visible' });
  requireCondition(await locator.count() === 1, code);
  return locator;
}

/** Validate exact source linkage and a single completed action against the real import response. */
function validateImport(result, goal, expectedCriterionId, title) {
  const source = result?.source;
  requireCondition(typeof result?.duplicate === 'boolean' && Array.isArray(result.evidence), 'IMPORT_RESPONSE_SHAPE');
  requireCondition(source?.kind === 'text' && source.goalId === goal.id && source.text === sourceBody && typeof source.id === 'string', 'SOURCE_BODY_OR_GOAL_MISMATCH');
  requireCondition(result.duplicate || source.title === title, 'SOURCE_TITLE_MISMATCH');
  requireCondition(result.evidence.length === 1, 'AMBIGUOUS_IMPORT_EVIDENCE');
  const item = result.evidence[0];
  requireCondition(item.sourceId === source.id && item.goalId === goal.id && item.criterionId === expectedCriterionId && item.eventType === 'completed_action', 'UNEXPECTED_COMPLETED_ACTION');
  requireCondition(typeof item.id === 'string' && typeof item.summary === 'string' && item.summary.length > 0 && typeof item.quote === 'string' && item.quote.length > 0, 'INVALID_EVIDENCE');
  requireCondition(Number.isInteger(item.textStart) && Number.isInteger(item.textEnd) && item.textStart >= 0 && item.textEnd > item.textStart && item.textEnd <= sourceBody.length && sourceBody.slice(item.textStart, item.textEnd) === item.quote, 'QUOTE_MISMATCH');
  requireCondition(Number.isInteger(item.revision) && item.revision >= 1, 'INVALID_EVIDENCE_REVISION');
  requireCondition(['proposed', 'confirmed', 'rejected', 'disputed'].includes(item.status), 'INVALID_EVIDENCE_STATUS');
  requireCondition(result.duplicate || item.status === 'proposed', 'NEW_EVIDENCE_ALREADY_REVIEWED');
  return { source, item };
}

/** Run UI actions in an isolated context and finalize the video only after context.close(). */
async function record(config) {
  const requireFromClient = createRequire(path.join(projectRoot, 'app/builds/typescript/client_web/package.json'));
  const { chromium } = requireFromClient('playwright');
  await fs.mkdir(config.output, { recursive: true, mode: 0o700 });
  const runDir = await fs.mkdtemp(path.join(config.output, 'run-'));
  const pendingDir = path.join(runDir, 'pending');
  const metadata = {
    schemaVersion: 1, kind: 'real-ui-recording', mode: 'text', status: 'RUNNING',
    startedAt: new Date().toISOString(), finishedAt: null,
    candidateSha: config.sha, candidateShaProvenance: config.sha ? 'operator-provided-not-independently-verified' : 'not-provided',
    viewport: { width: 1440, height: 900 }, syntheticData: true,
    sourceBodySha256: null, steps: [], duplicate: null, confirmationAttempted: false, confirmationPerformed: false,
    providerCall: 'not-observable-from-browser', video: null, failure: null,
  };
  const { createHash } = await import('node:crypto');
  metadata.sourceBodySha256 = createHash('sha256').update(sourceBody).digest('hex');
  let browser, context, page, video;
  let stage = 'launch';
  function step(name, details = {}) { metadata.steps.push({ name, at: new Date().toISOString(), ...details }); }
  function fail(error) {
    metadata.status = 'FAILED';
    metadata.failure ??= { stage, code: error instanceof RecordingError ? error.code : 'UI_ACTION_OR_BROWSER_FAILED' };
  }
  const waitResponse = (pathname, method) => page.waitForResponse(response => matchesResponse(response, config.origin, pathname, method), { timeout: config.timeout });
  const requestAndResponse = async (pathname, method, action) => {
    // Promise.all installs the listener first and observes either rejection immediately.
    const [response] = await Promise.all([waitResponse(pathname, method), action()]);
    return response;
  };
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    context = await browser.newContext({ viewport: metadata.viewport, recordVideo: { dir: pendingDir, size: metadata.viewport }, serviceWorkers: 'block' });
    page = await context.newPage();
    video = page.video();
    page.setDefaultTimeout(Math.min(config.timeout, 20000));
    stage = 'login';
    await page.goto(config.url, { waitUntil: 'domcontentloaded' });
    requireCondition(new URL(page.url()).origin === config.origin, 'CROSS_ORIGIN_LOGIN_FORBIDDEN');
    await uniqueVisible(page.locator('#identifier'), 'LOGIN_IDENTIFIER_AMBIGUOUS');
    await uniqueVisible(page.locator('#password[type="password"]'), 'LOGIN_PASSWORD_AMBIGUOUS');
    await page.locator('#identifier').fill(config.username);
    await page.locator('#password').fill(config.password);
    const [goalResponse, progressResponse] = await Promise.all([
      waitResponse(goalPath, 'GET'), waitResponse(`${goalPath}/progress`, 'GET'),
      page.getByRole('button', { name: 'Войти', exact: true }).click(),
    ]);
    const { goal } = await payload(goalResponse, 'GOAL');
    const { progress: initialProgress } = await payload(progressResponse, 'INITIAL_PROGRESS');
    await uniqueVisible(page.locator('#gw-goal-title'), 'PREPARED_GOAL_MISSING');
    requireCondition(goal?.id === 'demo' && goal.title === goalTitle && goal.confirmedAt && Array.isArray(goal.criteria), 'PREPARED_GOAL_MISMATCH');
    requireCondition(await page.locator('#gw-goal-title').textContent() === goalTitle, 'VISIBLE_GOAL_MISMATCH');
    requireCondition(await page.locator('.gw-demo-banner').count() === 0 && !new URL(page.url()).searchParams.has('preview'), 'FIXTURE_PREVIEW_FORBIDDEN');
    const criteria = goal.criteria.filter(item => criterionDescriptions.includes(item.description));
    requireCondition(criteria.length === 1, 'INTERVIEW_CRITERION_MISSING_OR_AMBIGUOUS');
    const criterion = criteria[0];
    const initial = initialProgress?.criteria?.find(item => item.criterionId === criterion.id);
    requireCondition(initialProgress?.goalId === goal.id && Number.isInteger(initial?.confirmedCount), 'INITIAL_PROGRESS_MISSING');
    await page.locator('.gw-workspace-grid[aria-busy="false"]').waitFor();
    step('ordinary_login_and_prepared_goal_verified');

    stage = 'import';
    await page.getByRole('button', { name: 'Добавить контекст', exact: true }).click();
    const form = await uniqueVisible(page.locator('#gw-import'), 'IMPORT_FORM_MISSING');
    await form.getByRole('button', { name: 'Текст', exact: true }).click();
    const title = `Синтетическое пробное интервью ${new Date().toISOString()} ${path.basename(runDir)}`;
    await form.getByLabel('Название источника', { exact: true }).fill(title);
    await form.getByLabel('Текст источника', { exact: false }).fill(sourceBody);
    const importResponse = await requestAndResponse('/api/context/import', 'POST', () => form.getByRole('button', { name: 'Найти события', exact: true }).click());
    const posted = importResponse.request().postDataJSON();
    requireCondition(posted.goalId === goal.id && posted.title === title && posted.text === sourceBody, 'IMPORT_REQUEST_MISMATCH');
    const imported = await payload(importResponse, 'IMPORT');
    const { source, item } = validateImport(imported, goal, criterion.id, title);
    metadata.duplicate = imported.duplicate;
    metadata.providerCall = imported.duplicate ? 'not-claimed-duplicate-result' : 'not-observable-from-browser';
    step('real_ui_import_response_verified', { duplicate: imported.duplicate });
    await page.locator('.gw-workspace-grid[aria-busy="false"]').waitFor();
    requireCondition(await page.locator('.gw-error').count() === 0, 'UI_IMPORT_ERROR');

    stage = 'source_and_quote';
    const row = await uniqueVisible(page.locator('.gw-event-completed_action').filter({ has: page.getByRole('heading', { name: item.summary, exact: true }) }), 'EVENT_ROW_AMBIGUOUS');
    requireCondition(await row.locator('.gw-event-criterion').textContent() === criterion.description, 'VISIBLE_CRITERION_MISMATCH');
    const sourceResponse = await requestAndResponse(`/api/sources/${encodeURIComponent(source.id)}`, 'GET', () => row.getByRole('button', { name: 'Посмотреть источник', exact: true }).click());
    const { source: openedSource } = await payload(sourceResponse, 'SOURCE');
    requireCondition(openedSource?.id === source.id && openedSource.goalId === goal.id && openedSource.text === sourceBody && openedSource.title === source.title, 'OPENED_SOURCE_MISMATCH');
    const sourcePanel = await uniqueVisible(page.locator('#gw-source'), 'SOURCE_PANEL_MISSING');
    await sourcePanel.locator('.gw-source-title').waitFor();
    requireCondition(await sourcePanel.locator('.gw-source-title').textContent() === source.title, 'VISIBLE_SOURCE_TITLE_MISMATCH');
    const mark = await uniqueVisible(sourcePanel.locator('.gw-source-document mark'), 'QUOTE_NOT_HIGHLIGHTED');
    requireCondition(await mark.textContent() === item.quote, 'VISIBLE_QUOTE_MISMATCH');
    requireCondition(await row.getAttribute('class').then(value => value.includes('is-selected')), 'EVENT_SELECTION_MISMATCH');
    await sourcePanel.scrollIntoViewIfNeeded();
    step('exact_source_and_quote_opened');

    if (imported.duplicate) {
      // Never re-confirm or reverse an existing review on a repeated run.
      stage = 'duplicate';
      const notice = await uniqueVisible(page.locator('.gw-notice'), 'DUPLICATE_NOTICE_NOT_VISIBLE');
      requireCondition(await notice.textContent() === 'Этот источник уже импортирован. Повторные события не добавлены.', 'DUPLICATE_NOTICE_MISMATCH');
      metadata.status = 'DUPLICATE';
      step('duplicate_reported_without_confirmation');
    } else {
      stage = 'confirm';
      const confirm = await uniqueVisible(row.getByRole('button', { name: 'Подтвердить', exact: true }), 'CONFIRM_BUTTON_AMBIGUOUS');
      metadata.confirmationAttempted = true;
      metadata.confirmationPerformed = null;
      step('confirmation_attempt_started');
      // Observe refresh concurrently, but do not delay an actual PATCH error until its timeout.
      const freshProgress = waitResponse(`${goalPath}/progress`, 'GET')
        .then(response => ({ response }), () => ({ response: null }));
      const reviewResponse = await requestAndResponse(`/api/evidence/${encodeURIComponent(item.id)}`, 'PATCH', () => confirm.click());
      const reviewInput = reviewResponse.request().postDataJSON();
      requireCondition(reviewInput.status === 'confirmed' && reviewInput.expectedRevision === item.revision, 'CONFIRM_REQUEST_MISMATCH');
      const { evidence: reviewed } = await payload(reviewResponse, 'CONFIRM');
      requireCondition(reviewed?.id === item.id && reviewed.sourceId === source.id && reviewed.criterionId === criterion.id && reviewed.eventType === 'completed_action' && reviewed.status === 'confirmed', 'CONFIRM_RESPONSE_MISMATCH');
      // A successful mutation may precede a UI refresh failure. Record the mutation immediately.
      metadata.confirmationPerformed = true;
      step('one_completed_action_confirmed');
      const { response: freshProgressResponse } = await freshProgress;
      requireCondition(freshProgressResponse !== null, 'PROGRESS_REFRESH_RESPONSE_MISSING');
      const { progress } = await payload(freshProgressResponse, 'FRESH_PROGRESS');
      const count = progress?.criteria?.find(entry => entry.criterionId === criterion.id)?.confirmedCount;
      requireCondition(progress?.goalId === goal.id && count === initial.confirmedCount + 1, 'PROGRESS_DID_NOT_INCREASE_BY_ONE');
      await page.locator('.gw-workspace-grid[aria-busy="false"]').waitFor();
      await row.locator('.gw-status-confirmed').waitFor();
      requireCondition(await page.locator('.gw-error').count() === 0, 'UI_REVIEW_ERROR');
      step('server_progress_increased_by_one', { before: initial.confirmedCount, after: count });
      metadata.status = 'COMPLETED_TEXT';
    }
    // Keep the final real UI frame visible. This is presentation pacing, not a simulated response.
    await page.waitForTimeout(1500);
  } catch (error) {
    fail(error);
  } finally {
    stage = 'finalize_video';
    try { await context?.close(); } catch (error) { fail(error); }
    try { await browser?.close(); } catch (error) { fail(error); }
    if (video) {
      try {
        const rawPath = await video.path();
        const label = metadata.status === 'FAILED' ? 'failed' : metadata.status === 'DUPLICATE' ? 'duplicate-text' : 'completed-text';
        const destination = path.join(runDir, label);
        await fs.mkdir(destination, { mode: 0o700 });
        await fs.rename(rawPath, path.join(destination, 'demo.webm'));
        metadata.video = { available: true, relativePath: `${label}/demo.webm` };
      } catch (error) {
        fail(error);
        metadata.video = { available: false, relativePath: null };
      }
    }
    if (metadata.status === 'RUNNING') fail(new RecordingError('INCOMPLETE_RECORDING'));
    metadata.finishedAt = new Date().toISOString();
    await fs.writeFile(path.join(runDir, 'metadata.json'), `${JSON.stringify(metadata, null, 2)}\n`, { mode: 0o600 });
    console.log(`Recording result: ${metadata.status}. Metadata saved in the configured output directory.`);
  }
  if (metadata.status === 'FAILED') process.exitCode = 1;
}

if (process.argv.includes('--help')) {
  console.log('Real UI text recording harness. Requires RYADOM_DEMO_URL, RYADOM_DEMO_USERNAME, RYADOM_DEMO_PASSWORD. Optional RYADOM_DEMO_OUTPUT_DIR, RYADOM_DEMO_SHA, RYADOM_DEMO_TIMEOUT_MS. USERNAME/PASSWORD/OUTPUT_DIR aliases are accepted. Uses installed Chrome and the client_web Playwright package. Does not start an app or create/reset goals. Audio automation is not implemented.');
} else {
  try {
    requireCondition(process.argv.length === 2, 'UNSUPPORTED_CLI_ARGUMENTS');
    await record(await configuration());
  }
  catch (error) {
    console.error(`Recording did not complete: ${error instanceof RecordingError ? error.code : 'SETUP_OR_OUTPUT_FAILED'}. No raw error or credentials are logged.`);
    process.exitCode = 1;
  }
}
